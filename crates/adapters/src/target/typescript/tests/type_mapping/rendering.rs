use std::path::Path;

use sqlay_app::TargetGenerator;
use sqlay_core as core;

use super::super::super::files::TypeScriptTargetGenerator;
use super::super::support::{file_contents, param, sql_segment};
use super::support::{
    column_override, column_ref, compilation_plan_with_mapping, core_type_override, enum_type_ref,
    import, named_override,
};

#[test]
fn generator_renders_static_type_mapping_annotations_imports_and_enum_unions() {
    let order_total = column_ref(None, "orders", "total_amount");
    let order_status = column_ref(None, "orders", "status");
    let mapping = core::TypeScriptTypeMappingConfig::new(
        vec![core_type_override(
            core::CoreType::DateTime,
            "IsoDateTime",
            None,
        )],
        vec![column_override(
            order_total.clone(),
            "MoneyAmount",
            Some(import("@/domain/money", "MoneyAmount")),
        )],
        vec![core::BuilderTypeOverrides::new(
            "listOrders".to_owned(),
            vec![named_override("id", "OrderId", None)],
            Vec::new(),
            Vec::new(),
        )],
    );
    let plan = compilation_plan_with_mapping(mapping);
    let query = core::CompiledQuery::new(
        core::QueryId::new("listOrders".to_owned()),
        "SELECT id, total_amount AS totalAmount, status, created_at AS createdAt FROM orders WHERE total_amount >= ?;".to_owned(),
        core::Cardinality::Many,
        vec![
            core::InputField::new("minimumAmount".to_owned(), core::CoreType::Decimal, true)
                .with_schema_column_reference(order_total.clone()),
        ],
        vec![
            core::ResultColumn::new("id".to_owned(), core::CoreType::Int64, false),
            core::ResultColumn::new("totalAmount".to_owned(), core::CoreType::Decimal, true)
                .with_schema_column_reference(order_total.clone()),
            core::ResultColumn::new_type_ref(
                "status".to_owned(),
                enum_type_ref(["draft", "paid"]),
                false,
            )
            .with_schema_column_reference(order_status),
            core::ResultColumn::new("createdAt".to_owned(), core::CoreType::DateTime, false),
        ],
    )
    .with_params(vec![
        core::ParamBinding::new("minimumAmount".to_owned(), core::CoreType::Decimal, true)
            .with_schema_column_reference(order_total),
    ])
    .with_source_path("sql/orders.sql");

    let files = TypeScriptTargetGenerator
        .generate(&plan, &[core::CompiledBuilder::Query(query)])
        .expect("type-mapped query should generate");
    let contents = file_contents(
        &files,
        Path::new("/tmp/sqlay-project/src/generated/sqlay/sql/orders.ts"),
    );

    assert!(contents.starts_with(
        "// @generated by sqlay. Do not edit.\n\n\
import type { MoneyAmount } from \"@/domain/money\";\n\n\
export type listOrders_Input"
    ));
    assert_eq!(contents.matches("MoneyAmount } from").count(), 1);
    assert!(contents.contains("  minimumAmount: MoneyAmount | null;\n"));
    assert!(contents.contains("  id: OrderId;\n"));
    assert!(contents.contains("  totalAmount: MoneyAmount | null;\n"));
    assert!(contents.contains("  status: \"draft\" | \"paid\";\n"));
    assert!(contents.contains("  createdAt: IsoDateTime;\n"));
    assert!(contents.contains("params: readonly [MoneyAmount | null]"));
}

#[test]
fn generator_renders_dynamic_input_type_mapping_without_narrowing_params_array() {
    let user_email = column_ref(None, "users", "email");
    let mapping = core::TypeScriptTypeMappingConfig::new(
        Vec::new(),
        vec![column_override(
            user_email.clone(),
            "EmailAddress",
            Some(import("@/domain/email", "EmailAddress")),
        )],
        vec![core::BuilderTypeOverrides::new(
            "searchOrders".to_owned(),
            Vec::new(),
            vec![named_override(
                "tenantId",
                "TenantId",
                Some(import("@/domain/tenant", "TenantId")),
            )],
            vec![core::RepeatTypeOverrides::new(
                "ids".to_owned(),
                vec![named_override(
                    "id",
                    "OrderId",
                    Some(import("@/domain/order", "OrderId")),
                )],
            )],
        )],
    );
    let plan = compilation_plan_with_mapping(mapping);
    let email_branch = core::CompiledSlotBranch::new(
        "byEmail".to_owned(),
        vec![sql_segment(
            " AND email = ?",
            vec![
                param("email", core::CoreType::String, false)
                    .with_schema_column_reference(user_email),
            ],
        )],
    );
    let dynamic_body = core::CompiledDynamicQuery::new_with_bodies(
        vec![
            core::CompiledSqlBody::new(
                vec![
                    sql_segment(
                        "SELECT id FROM orders WHERE tenant_id = ? AND id IN (",
                        vec![param("tenantId", core::CoreType::Int64, false)],
                    ),
                    sql_segment(")", Vec::new()),
                ],
                vec![core::CompiledRepeatOccurrence::new(
                    "ids".to_owned(),
                    ",".to_owned(),
                    sql_segment("?", vec![param("id", core::CoreType::Int64, false)]),
                )],
            ),
            core::CompiledSqlBody::from_segment(sql_segment(";", Vec::new())),
        ],
        vec![core::CompiledSlotOccurrence::new("filter".to_owned())],
        vec![core::CompiledSlotDefinition::new(
            "filter".to_owned(),
            vec![email_branch],
        )],
        vec![core::CompiledRepeatDefinition::new(
            "ids".to_owned(),
            vec![param("id", core::CoreType::Int64, false)],
        )],
    );
    let query = core::CompiledQuery::new(
        core::QueryId::new("searchOrders".to_owned()),
        "SELECT id FROM orders WHERE tenant_id = ? AND id IN (?);".to_owned(),
        core::Cardinality::Many,
        vec![core::InputField::new(
            "tenantId".to_owned(),
            core::CoreType::Int64,
            false,
        )],
        vec![core::ResultColumn::new(
            "id".to_owned(),
            core::CoreType::Int64,
            false,
        )],
    )
    .with_params(vec![param("tenantId", core::CoreType::Int64, false)])
    .with_dynamic_body(dynamic_body)
    .with_source_path("sql/orders.sql");

    let files = TypeScriptTargetGenerator
        .generate(&plan, &[core::CompiledBuilder::Query(query)])
        .expect("dynamic query should generate with type-mapped inputs");
    let contents = file_contents(
        &files,
        Path::new("/tmp/sqlay-project/src/generated/sqlay/sql/orders.ts"),
    );

    assert!(contents.contains("import type { EmailAddress } from \"@/domain/email\";"));
    assert!(contents.contains("import type { OrderId } from \"@/domain/order\";"));
    assert!(contents.contains("import type { TenantId } from \"@/domain/tenant\";"));
    assert!(contents.contains("type SqlParam = unknown;"));
    assert!(contents.contains("  tenantId: TenantId;\n"));
    assert!(contents.contains("  ids: readonly [{ id: OrderId }, ...{ id: OrderId }[]];\n"));
    assert!(contents.contains("    email: EmailAddress;\n"));
    assert!(contents.contains("params: readonly SqlParam[]"));
    assert!(!contents.contains("params: readonly [TenantId"));
}
